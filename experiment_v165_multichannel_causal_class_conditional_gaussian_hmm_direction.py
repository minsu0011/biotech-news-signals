class TrainChannelScale:
    def __init__(self) -> None:
        self.median = np.zeros(CHANNEL_N, dtype=float)
        self.scale = np.ones(CHANNEL_N, dtype=float)

    def fit(self, path: np.ndarray) -> "TrainChannelScale":
        require(path.ndim == 3 and path.shape[1:] == (HORIZON_N, CHANNEL_N), "V165 train path shape invalid")
        flattened = path.reshape(-1, CHANNEL_N)
        self.median = np.median(flattened, axis=0)
        q25, q75 = np.quantile(flattened, [0.25, 0.75], axis=0)
        robust = (q75 - q25) / 1.349
        standard = np.std(flattened, axis=0)
        self.scale = np.where(robust > 1e-8, robust, np.where(standard > 1e-8, standard, 1.0))
        require(np.isfinite(self.median).all() and np.isfinite(self.scale).all(), "V165 channel scale invalid")
        return self

    def transform(self, path: np.ndarray) -> np.ndarray:
        result = np.clip((path - self.median[None, None, :]) / self.scale[None, None, :], -CHANNEL_CLIP, CHANNEL_CLIP)
        require(result.shape[1:] == (HORIZON_N, CHANNEL_N) and np.isfinite(result).all(), "V165 scaled path invalid")
        return result


def equal_event_group_paths(frame: pd.DataFrame, path: np.ndarray) -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    require(path.shape == (len(frame), HORIZON_N, CHANNEL_N), "V165 grouping path shape invalid")
    keys = frame.event_group_id.fillna("__MISSING_GROUP__").astype(str).to_numpy()
    target = frame.y.to_numpy(int)
    unique = np.unique(keys)
    grouped_path = np.empty((len(unique), HORIZON_N, CHANNEL_N), dtype=float)
    grouped_target = np.empty(len(unique), dtype=int)
    for index, key in enumerate(unique):
        mask = keys == key
        labels = np.unique(target[mask])
        require(labels.size == 1, "V165 event group crosses labels")
        grouped_path[index] = np.mean(path[mask], axis=0)
        grouped_target[index] = int(labels[0])
    require(np.unique(grouped_target).size == 2 and np.isfinite(grouped_path).all(), "V165 grouped path invalid")
    return grouped_path, grouped_target, {
        "raw_rows": len(frame), "equal_event_groups": len(unique),
        "duplicates_removed": len(frame) - len(unique),
        "class_event_group_n": np.bincount(grouped_target, minlength=2).tolist(),
        "equal_event_group_weighting": True,
        "group_path_sha256": array_sha256(grouped_path),
    }


def log_emission(sequence: np.ndarray, mean: np.ndarray, variance: np.ndarray) -> np.ndarray:
    difference = sequence[:, :, None, :] - mean[None, None, :, :]
    result = -0.5 * np.sum(
        np.log(2.0 * np.pi * variance)[None, None, :, :] + np.square(difference) / variance[None, None, :, :],
        axis=3,
    )
    require(np.isfinite(result).all(), "V165 emission log probability invalid")
    return result


def forward_backward(
    sequence: np.ndarray,
    initial: np.ndarray,
    transition: np.ndarray,
    mean: np.ndarray,
    variance: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    rows = len(sequence)
    emission = log_emission(sequence, mean, variance)
    log_initial = np.log(np.clip(initial, 1e-15, 1.0))
    log_transition = np.log(np.clip(transition, 1e-15, 1.0))
    alpha = np.empty((rows, HORIZON_N, STATE_N), dtype=float)
    alpha[:, 0, :] = log_initial[None, :] + emission[:, 0, :]
    for time in range(1, HORIZON_N):
        alpha[:, time, :] = emission[:, time, :] + logsumexp(
            alpha[:, time - 1, :, None] + log_transition[None, :, :], axis=1
        )
    log_likelihood = logsumexp(alpha[:, -1, :], axis=1)
    beta = np.zeros((rows, HORIZON_N, STATE_N), dtype=float)
    for time in range(HORIZON_N - 2, -1, -1):
        beta[:, time, :] = logsumexp(
            log_transition[None, :, :] + emission[:, time + 1, None, :] + beta[:, time + 1, None, :], axis=2
        )
    gamma = np.exp(alpha + beta - log_likelihood[:, None, None])
    gamma /= np.maximum(gamma.sum(axis=2, keepdims=True), 1e-15)
    transition_count = np.zeros((STATE_N, STATE_N), dtype=float)
    for time in range(HORIZON_N - 1):
        log_xi = (
            alpha[:, time, :, None] + log_transition[None, :, :]
            + emission[:, time + 1, None, :] + beta[:, time + 1, None, :]
            - log_likelihood[:, None, None]
        )
        transition_count += np.exp(log_xi).sum(axis=0)
    require(np.isfinite(log_likelihood).all() and np.isfinite(gamma).all() and np.isfinite(transition_count).all(), "V165 forward-backward invalid")
    return log_likelihood, gamma, transition_count


def initialize_hmm(sequence: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    segments = np.array_split(np.arange(HORIZON_N), STATE_N)
    mean = np.stack([np.mean(sequence[:, segment, :], axis=(0, 1)) for segment in segments], axis=0)
    pooled_variance = np.maximum(np.var(sequence.reshape(-1, CHANNEL_N), axis=0), VARIANCE_FLOOR)
    variance = np.repeat(pooled_variance[None, :], STATE_N, axis=0)
    initial = np.asarray([0.80, 0.15, 0.05], dtype=float)
    transition = np.asarray([
        [0.75, 0.20, 0.05],
        [0.08, 0.75, 0.17],
        [0.05, 0.10, 0.85],
    ], dtype=float)
    return initial, transition, mean, variance


def fit_gaussian_hmm(sequence: np.ndarray, label: int) -> tuple[dict[str, np.ndarray], dict[str, Any]]:
    require(sequence.ndim == 3 and sequence.shape[1:] == (HORIZON_N, CHANNEL_N), "V165 HMM sequence shape invalid")
    require(len(sequence) >= 100, f"V165 class {label} support too small")
    initial, transition, mean, variance = initialize_hmm(sequence)
    trace: list[float] = []
    for _ in range(HMM_ITERATIONS):
        log_likelihood, gamma, transition_count = forward_backward(sequence, initial, transition, mean, variance)
        trace.append(float(np.sum(log_likelihood)))
        initial_count = gamma[:, 0, :].sum(axis=0) + DIRICHLET_PSEUDOCOUNT
        initial = initial_count / initial_count.sum()
        transition_count += DIRICHLET_PSEUDOCOUNT
        transition = transition_count / transition_count.sum(axis=1, keepdims=True)
        occupancy = gamma.sum(axis=(0, 1))
        mean = np.einsum("ntk,ntd->kd", gamma, sequence) / np.maximum(occupancy[:, None], 1e-12)
        difference = sequence[:, :, None, :] - mean[None, None, :, :]
        variance = np.einsum("ntk,ntkd->kd", gamma, np.square(difference)) / np.maximum(occupancy[:, None], 1e-12)
        variance = np.maximum(variance, VARIANCE_FLOOR)
    final_likelihood, _, _ = forward_backward(sequence, initial, transition, mean, variance)
    trace.append(float(np.sum(final_likelihood)))
    packed = np.concatenate([initial.ravel(), transition.ravel(), mean.ravel(), variance.ravel()])
    require(np.isfinite(packed).all() and np.all(initial > 0.0) and np.all(transition > 0.0), "V165 HMM parameters invalid")
    model = {"initial": initial, "transition": transition, "mean": mean, "variance": variance}
    increments = np.diff(np.asarray(trace, dtype=float))
    return model, {
        "label": label, "sequence_n": len(sequence), "hidden_states": STATE_N,
        "iterations": HMM_ITERATIONS, "trace_first": trace[0], "trace_last": trace[-1],
        "trace_min_increment": float(np.min(increments)), "trace_positive_fraction": float(np.mean(increments >= -1e-8)),
        "initial_probability": initial.tolist(), "transition_matrix": transition.tolist(),
        "mean_sha256": array_sha256(mean), "variance_sha256": array_sha256(variance),
        "parameter_sha256": array_sha256(packed),
        "variance_min": float(np.min(variance)), "variance_max": float(np.max(variance)),
        "deterministic_fixed_iteration_baum_welch": True,
    }


def hmm_log_likelihood(sequence: np.ndarray, model: dict[str, np.ndarray]) -> np.ndarray:
    likelihood, _, _ = forward_backward(
        sequence, model["initial"], model["transition"], model["mean"], model["variance"]
    )
    return likelihood


