def local_cluster_weight(frame: pd.DataFrame) -> np.ndarray:
    sizes = frame.groupby("text_cluster_id").event_id.transform("size").clip(lower=1)
    return 1.0 / sizes.to_numpy(float)


def pcorrect_multiplier(probability: Iterable[float]) -> np.ndarray:
    values = np.asarray(list(probability), dtype=float)
    require(np.isfinite(values).all(), "V227_NONFINITE_PCORRECT")
    require(((values >= 0.0) & (values <= 1.0)).all(), "V227_PCORRECT_RANGE")
    multiplier = 0.5 + values
    require(((multiplier >= 0.5) & (multiplier <= 1.5)).all(),
            "V227_WEIGHT_TRANSFORM_RANGE")
    return multiplier


def outer_folds(frame: pd.DataFrame) -> list[tuple[pd.DataFrame, pd.DataFrame, int, dict[str, Any]]]:
    ordered = frame.sort_values(["event_time_utc", "event_id"], kind="mergesort").reset_index(drop=True)
    blocks = np.array_split(np.arange(len(ordered)), OUTER_BLOCKS)
    output = []
    for fold in range(1, OUTER_BLOCKS):
        valid = ordered.iloc[blocks[fold]].copy()
        valid_start = pd.Timestamp(valid.event_time_utc.min())
        train = ordered[ordered.event_time_utc < valid_start - EMBARGO].copy()
        before_purge = len(train)
        valid_clusters = set(valid.text_cluster_id)
        train = train[~train.text_cluster_id.isin(valid_clusters)].copy()
        require(len(train) >= 120 and len(valid) >= 100 and train.y.nunique() == 2,
                f"V227_OUTER_SUPPORT_FAIL:{fold}")
        train_end = pd.Timestamp(train.event_time_utc.max())
        overlap = len(set(train.text_cluster_id) & valid_clusters)
        require(train_end < valid_start - EMBARGO and overlap == 0,
                f"V227_OUTER_LEAKAGE:{fold}")
        audit = {
            "outer_fold": fold, "train_n": len(train), "valid_n": len(valid),
            "valid_start": valid_start, "train_end": train_end,
            "embargo_minutes": 35.0,
            "text_cluster_purge_n": before_purge - len(train),
            "text_cluster_overlap_n": overlap,
        }
        output.append((train.reset_index(drop=True), valid.reset_index(drop=True), fold, audit))
    return output


def inner_split(train: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    ordered = train.sort_values(["event_time_utc", "event_id"], kind="mergesort").reset_index(drop=True)
    split = max(90, int(INNER_FRACTION * len(ordered)))
    valid = ordered.iloc[split:].copy()
    valid_start = pd.Timestamp(valid.event_time_utc.min())
    base = ordered[ordered.event_time_utc < valid_start - EMBARGO].copy()
    before = len(base)
    base = base[~base.text_cluster_id.isin(set(valid.text_cluster_id))].copy()
    overlap = len(set(base.text_cluster_id) & set(valid.text_cluster_id))
    require(len(base) >= 70 and len(valid) >= 30 and base.y.nunique() == 2,
            "V227_INNER_SUPPORT_FAIL")
    require(pd.Timestamp(base.event_time_utc.max()) < valid_start - EMBARGO and overlap == 0,
            "V227_INNER_LEAKAGE")
    return base.reset_index(drop=True), valid.reset_index(drop=True), {
        "inner_train_n": len(base), "inner_valid_n": len(valid),
        "inner_train_end": pd.Timestamp(base.event_time_utc.max()),
        "inner_valid_start": valid_start, "inner_embargo_minutes": 35.0,
        "inner_text_cluster_purge_n": before - len(base),
        "inner_text_cluster_overlap_n": overlap,
    }


